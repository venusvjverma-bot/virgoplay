-- Client Purchase Actions migration. Full narrative header is preserved in
-- supabase/migrations/20261018143000_client_purchase_actions.sql (kept for
-- readability). This applies the exact same function + grant, abridged.

CREATE OR REPLACE FUNCTION client_purchase_action(
  p_client_id     uuid,
  p_session_token text,
  p_action        text,
  p_package_id    text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  -- Server-side package definitions: the ONLY trusted source for
  -- pricing/credits during fulfillment. Never trust browser values.
  v_pkg_id        text;
  v_pkg_name      text;
  v_pkg_credits   integer;
  v_pkg_price     numeric(12,2);
  v_pkg_currency  text;
  v_client_active boolean;
  v_order         client_credit_orders%ROWTYPE;
  v_result        jsonb;
  v_test_mode     constant boolean := true;  -- TEST_SIMULATION_ENABLED flag
BEGIN
  -- ── 0. Identity: session token must verify server-side ────────────────
  IF p_client_id IS NULL OR p_session_token IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Missing client id or session token');
  END IF;

  IF NOT verify_client_session(p_client_id, p_session_token) THEN
    RETURN jsonb_build_object('success', false, 'error', 'Unauthorized: invalid or expired session');
  END IF;

  IF p_action NOT IN ('create', 'cancel', 'simulate_payment') THEN
    RETURN jsonb_build_object('success', false, 'error', 'Unknown action');
  END IF;

  -- Client must exist and be active
  SELECT is_active INTO v_client_active FROM clients WHERE id = p_client_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'Client not found');
  END IF;
  IF NOT v_client_active THEN
    RETURN jsonb_build_object('success', false, 'error', 'Account is not active');
  END IF;

  -- ── 1. Resolve the package from server-side definitions ───────────────
  v_pkg_id := lower(trim(COALESCE(p_package_id, '')));
  IF v_pkg_id = 'starter' THEN
    v_pkg_name := 'Starter';  v_pkg_credits := 100;  v_pkg_price := 0.99;
  ELSIF v_pkg_id = 'plus' THEN
    v_pkg_name := 'Plus';     v_pkg_credits := 500;  v_pkg_price := 2.99;
  ELSIF v_pkg_id = 'premium' THEN
    v_pkg_name := 'Premium';  v_pkg_credits := 1500; v_pkg_price := 7.99;
  ELSE
    v_pkg_name := NULL; v_pkg_credits := NULL; v_pkg_price := NULL;
  END IF;
  v_pkg_currency := 'USD';

  -- ── 2. Action: create ──────────────────────────────────────────────────
  IF p_action = 'create' THEN
    IF v_pkg_credits IS NULL THEN
      RETURN jsonb_build_object('success', false, 'error', 'Unknown package');
    END IF;

    INSERT INTO client_credit_orders (client_id, package_id, package_name,
                                      credit_amount, price_amount, currency)
    VALUES (p_client_id, v_pkg_id, v_pkg_name, v_pkg_credits, v_pkg_price, v_pkg_currency)
    RETURNING * INTO v_order;

    RETURN jsonb_build_object(
      'success', true,
      'order', jsonb_build_object(
        'order_id', v_order.order_id,
        'package_id', v_order.package_id,
        'package_name', v_order.package_name,
        'credit_amount', v_order.credit_amount,
        'price_amount', v_order.price_amount,
        'currency', v_order.currency,
        'status', v_order.status,
        'created_at', v_order.created_at
      )
    );
  END IF;

  -- ── 3. Actions cancel / simulate_payment operate on the caller's OWN
  --     pending order. The order_id itself is generated by the database,
  --     so the caller identifies the order by the package they selected —
  --     the newest pending order for their own client id. ────────────────
  IF v_pkg_credits IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Unknown package');
  END IF;

  SELECT * INTO v_order
    FROM client_credit_orders
    WHERE client_id = p_client_id
      AND package_id = v_pkg_id
      AND credit_amount = v_pkg_credits
      AND price_amount = v_pkg_price
      AND currency = v_pkg_currency
      AND status = 'pending'
    ORDER BY created_at DESC
    LIMIT 1
    FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'No pending order found for this package');
  END IF;

  -- ── 4. Action: cancel ──────────────────────────────────────────────────
  IF p_action = 'cancel' THEN
    UPDATE client_credit_orders
      SET status = 'cancelled', failure_reason = 'Cancelled by client'
      WHERE order_id = v_order.order_id;

    RETURN jsonb_build_object('success', true, 'order_id', v_order.order_id, 'status', 'cancelled');
  END IF;

  -- ── 5. Action: simulate_payment (TEST-ONLY) ───────────────────────────
  IF NOT v_test_mode THEN
    INSERT INTO client_credit_order_events (order_id, event_type, detail)
    VALUES (v_order.order_id, 'rejected',
      jsonb_build_object('reason', 'test simulation disabled', 'action', 'simulate_payment'));
    RETURN jsonb_build_object('success', false, 'error', 'Test simulation is disabled');
  END IF;

  -- Defense in depth: re-validate the stored order against the trusted
  -- server-side definitions before granting anything.
  IF v_order.package_id <> v_pkg_id OR v_order.credit_amount <> v_pkg_credits
     OR v_order.price_amount <> v_pkg_price OR upper(v_order.currency) <> upper(v_pkg_currency) THEN
    UPDATE client_credit_orders
      SET failure_reason = 'Rejected: order does not match server-side package definition'
      WHERE order_id = v_order.order_id;
    INSERT INTO client_credit_order_events (order_id, event_type, detail)
    VALUES (v_order.order_id, 'rejected',
      jsonb_build_object('reason', 'order does not match server-side package definition',
                         'action', 'simulate_payment'));
    RETURN jsonb_build_object('success', false, 'error', 'Order does not match the package definition');
  END IF;

  -- Hand off to the EXISTING, unmodified fulfillment primitive. It
  -- enforces: pending-only, exact amount/currency match, row locking,
  -- idempotency (already_fulfilled without re-grant), atomic
  -- paid+grant+history, and event logging.
  v_result := client_fulfill_paid_order(
    p_order_id         => v_order.order_id,
    p_provider         => 'test-simulation',
    p_provider_txn_ref => 'test-simulation:' || v_order.order_id,
    p_amount           => v_order.price_amount,
    p_currency         => v_order.currency
  );

  RETURN v_result;
END;
$$;

GRANT EXECUTE ON FUNCTION client_purchase_action(uuid, text, text, text) TO anon, authenticated;
