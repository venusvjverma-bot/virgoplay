/*
# Client Credit Purchase Orders — Secure Foundation

1. New Table: `client_credit_orders`
   Records future credit purchases. No rows are created by this migration —
   the table starts empty. Orders will be written in the future ONLY by
   trusted server-side code (edge functions / payment provider integration)
   once a real payment provider is connected. No pricing or currency is
   assumed: `price_amount` and `currency` are nullable until finalised.

   Columns:
   - `id` (uuid, primary key) — internal row id.
   - `order_id` (text, unique, not null) — public-facing unique order
     reference, e.g. VPO-20261018-1A2B3C4D, generated by the database.
   - `client_id` (uuid, not null) — the purchasing client. References
     clients(id) ON DELETE CASCADE. NEVER supplied or trusted from the
     browser: ownership is always established server-side.
   - `package_id` (text, not null) — identifier of the purchased package
     (e.g. 'starter', 'plus', 'premium').
   - `package_name` (text, nullable) — human-readable package name snapshot.
   - `credit_amount` (integer, not null) — credits the package represents.
     No credits are granted by this migration.
   - `price_amount` (numeric(12,2), nullable) — price at purchase time.
     Nullable because pricing is not finalised.
   - `currency` (text, nullable) — ISO currency code. Nullable because
     currency is not finalised.
   - `payment_provider` (text, nullable) — provider name (e.g. 'stripe').
   - `provider_transaction_ref` (text, nullable) — the provider's own
     transaction id. A partial UNIQUE index prevents the same provider
     reference being recorded twice.
   - `status` (text, not null, default 'pending') — one of pending, paid,
     failed, cancelled, refunded (enforced by a CHECK constraint).
   - `created_at` / `updated_at` (timestamptz, not null, defaults now()) —
     updated_at is maintained by a trigger.

2. Security
   - RLS enabled on `client_credit_orders`.
   - NO RLS policies and NO table grants for anon or authenticated:
     the browser can NEVER read or write this table directly. This follows
     the same deny-by-default pattern as `client_sessions`.
   - All reads go through the new session-token-verified RPC below, which
     establishes the caller's identity server-side (a bare client_id from
     the browser is never trusted).
   - No EXECUTE grant is given for any function that could create orders or
     mark them paid — such operations do not exist yet and will only be
     added with a verified payment provider. Clients can read their own
     order history; nothing else.

3. New Function: `client_get_purchase_history(p_client_id, p_session_token)`
   SECURITY DEFINER, callable by anon and authenticated. Returns the
   caller's own purchase orders as JSON, ONLY after `verify_client_session`
   confirms the session token matches the client id (server-validated,
   hashed-token check against `client_sessions`).

4. Important Notes
   1. No existing tables, policies, grants, or RPCs are modified — existing
      credit balances, spending history, media unlocks, creator wallets and
      session behaviour are untouched.
   2. No payment gateway is connected; no rows are inserted; no credits are
      granted, deducted, or changed.
   3. Duplicate order processing: the unique order_id and the unique
      (payment_provider, provider_transaction_ref) index give idempotency
      anchors for the future payment-integration work.
*/

-- ═══════════════════════════════════════════════════════════════════════════
-- 1. Table
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS client_credit_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id text NOT NULL UNIQUE
    DEFAULT 'VPO-' || to_char(now(), 'YYYYMMDD') || '-' || upper(substring(gen_random_uuid()::text from 1 for 8)),
  client_id uuid NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  package_id text NOT NULL,
  package_name text,
  credit_amount integer NOT NULL,
  price_amount numeric(12,2),
  currency text,
  payment_provider text,
  provider_transaction_ref text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'paid', 'failed', 'cancelled', 'refunded')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ═══════════════════════════════════════════════════════════════════════════
-- 2. Indexes
-- ═══════════════════════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS idx_client_credit_orders_client
  ON client_credit_orders(client_id, created_at DESC);

-- Prevents the same provider transaction reference from being recorded twice
-- (idempotency anchor for the future payment-provider integration).
CREATE UNIQUE INDEX IF NOT EXISTS idx_client_credit_orders_provider_ref
  ON client_credit_orders(payment_provider, provider_transaction_ref)
  WHERE provider_transaction_ref IS NOT NULL;

-- ═══════════════════════════════════════════════════════════════════════════
-- 3. updated_at trigger
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION client_credit_orders_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_client_credit_orders_updated_at ON client_credit_orders;
CREATE TRIGGER trg_client_credit_orders_updated_at
  BEFORE UPDATE ON client_credit_orders
  FOR EACH ROW EXECUTE FUNCTION client_credit_orders_touch_updated_at();

-- ═══════════════════════════════════════════════════════════════════════════
-- 4. Security: RLS enabled, deny-by-default for anon/authenticated
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE client_credit_orders ENABLE ROW LEVEL SECURITY;

-- No policies for anon/authenticated — direct browser access is fully denied.
-- Future order writes happen exclusively via trusted server-side code
-- (service role edge functions), which bypasses RLS.
REVOKE ALL ON client_credit_orders FROM anon, authenticated;

-- ═══════════════════════════════════════════════════════════════════════════
-- 5. Session-token-verified read RPC (own orders only)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION client_get_purchase_history(
  p_client_id     uuid,
  p_session_token text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT verify_client_session(p_client_id, p_session_token) THEN
    RETURN jsonb_build_object('success', false, 'error', 'Unauthorized: invalid or expired session');
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'orders', (
      SELECT COALESCE(jsonb_agg(order_row ORDER BY order_row.created_at DESC), '[]'::jsonb)
      FROM (
        SELECT jsonb_build_object(
          'order_id', o.order_id,
          'package_id', o.package_id,
          'package_name', o.package_name,
          'credit_amount', o.credit_amount,
          'price_amount', o.price_amount,
          'currency', o.currency,
          'payment_provider', o.payment_provider,
          'provider_transaction_ref', o.provider_transaction_ref,
          'status', o.status,
          'created_at', o.created_at,
          'updated_at', o.updated_at
        ) AS order_row
        FROM client_credit_orders o
        WHERE o.client_id = p_client_id
      ) sub
    )
  );
END;
$$;

GRANT EXECUTE ON FUNCTION client_get_purchase_history(uuid, text) TO anon, authenticated;
